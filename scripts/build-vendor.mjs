import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';

await build({
  entryPoints: ['scripts/lit-runtime.js'],
  outfile: 'assets/lit-runtime.js',
  bundle: true,
  minify: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2020',
  legalComments: 'inline',
  banner: { js: '// Generated by npm run build:vendor. Licenses: lit-runtime.LICENSE.txt' },
});

const packages = ['lit', 'lit-element', 'lit-html', '@lit/reactive-element', '@lit/task'];
const licenses = await Promise.all(packages.map(async (name) =>
  `${name}\n\n${await readFile(`node_modules/${name}/LICENSE`, 'utf8')}`
));
await writeFile('assets/lit-runtime.LICENSE.txt', licenses.join('\n\n'));
